export function parseRich(text) {
  return String(text).replace(
    /\[\[(\w+):([^\|\]]+)\|([^\]]+)\]\]/g,
    (_m, kind, id, label) =>
      `<a href="#${kind}-${id}" data-link="${kind}:${id}">${escapeText(label)}</a>`
  );
}

export function escapeText(s) {
  return String(s ?? "")
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}
